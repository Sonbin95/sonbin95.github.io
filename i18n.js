const LANG_STORAGE_KEY = "lumiapps_lang";

function getI18nValue(langCode, key) {
  const dict = I18N[langCode] || I18N.vi;
  const parts = key.split(".");
  let node = dict;
  for (const p of parts) {
    node = node && node[p];
  }
  if (node === undefined) {
    // fall back to Vietnamese source content if a key is missing
    node = parts.reduce((n, p) => n && n[p], I18N.vi);
  }
  return node;
}

function applyLanguage(langCode) {
  if (!I18N[langCode]) return;
  document.documentElement.lang = langCode;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const value = getI18nValue(langCode, key);
    if (value === undefined) return;

    if (el.tagName === "META") {
      el.setAttribute("content", value);
    } else if (el.hasAttribute("data-i18n-html")) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  try {
    localStorage.setItem(LANG_STORAGE_KEY, langCode);
  } catch (e) {
    // localStorage unavailable (private mode, etc.) — ignore
  }
}

function getSavedLanguage() {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY);
  } catch (e) {
    return null;
  }
}
